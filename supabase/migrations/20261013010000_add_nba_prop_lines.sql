create table if not exists public.nba_prop_lines (
  id bigint generated by default as identity primary key,
  external_event_id text not null,
  player_name text not null,
  market text not null check (
    market in (
      'player_points',
      'player_rebounds',
      'player_assists',
      'player_threes',
      'player_points_rebounds_assists'
    )
  ),
  line numeric not null,
  over_price integer,
  under_price integer,
  bookmaker text not null,
  home_team text not null,
  away_team text not null,
  commence_time timestamptz not null,
  fetched_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists nba_prop_lines_event_idx
  on public.nba_prop_lines (external_event_id);

create index if not exists nba_prop_lines_player_market_idx
  on public.nba_prop_lines (player_name, market);

create index if not exists nba_prop_lines_commence_time_idx
  on public.nba_prop_lines (commence_time);

create index if not exists nba_prop_lines_bookmaker_market_idx
  on public.nba_prop_lines (bookmaker, market);

alter table public.nba_prop_lines enable row level security;
