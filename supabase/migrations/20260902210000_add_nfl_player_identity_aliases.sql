create table if not exists public.nfl_player_identity_aliases (
  id bigint generated by default as identity primary key,
  source text not null,
  source_player_name text not null,
  gsis_id text not null,
  canonical_player_name text not null,
  created_at timestamptz not null default now(),

  constraint nfl_player_identity_aliases_source_name_unique
    unique (source, source_player_name)
);

