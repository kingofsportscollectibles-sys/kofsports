-- NBA core data model.
-- Canonical player identity is the NBA PLAYER_ID supplied by NBA.com.
-- Canonical game identity is NBA GAME_ID and is stored as text
-- because NBA game IDs contain meaningful leading zeroes.

create table public.nba_games (
  id text primary key,
  season integer not null,
  game_type text not null,
  game_date date not null,
  commence_time timestamptz,
  home_team text not null,
  away_team text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  constraint nba_games_game_type_check
    check (game_type in ('preseason', 'regular', 'playoffs')),

  constraint nba_games_team_check
    check (home_team <> away_team)
);

create index nba_games_game_date_idx
  on public.nba_games (game_date desc);

create index nba_games_season_type_idx
  on public.nba_games (
    season,
    game_type,
    game_date
  );

create index nba_games_home_team_idx
  on public.nba_games (home_team);

create index nba_games_away_team_idx
  on public.nba_games (away_team);


create table public.nba_players (
  id bigint primary key,
  player_name text not null,
  team text,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index nba_players_team_idx
  on public.nba_players (team);

create index nba_players_name_idx
  on public.nba_players (lower(player_name));


create table public.nba_player_game_stats (
  id bigint generated by default as identity primary key,

  game_id text not null
    references public.nba_games(id)
    on delete cascade,

  player_id bigint not null
    references public.nba_players(id)
    on delete cascade,

  season integer not null,
  game_type text not null,
  game_date date not null,

  player_name text not null,
  team text not null,
  opponent text not null,
  is_home boolean not null,

  minutes numeric,

  field_goals_made integer,
  field_goals_attempted integer,
  three_pointers_made integer,
  three_pointers_attempted integer,
  free_throws_made integer,
  free_throws_attempted integer,

  offensive_rebounds integer,
  defensive_rebounds integer,
  rebounds integer,
  assists integer,
  steals integer,
  blocks integer,
  turnovers integer,
  personal_fouls integer,
  points integer,
  plus_minus integer,

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  constraint nba_player_game_stats_game_type_check
    check (game_type in ('preseason', 'regular', 'playoffs')),

  constraint nba_player_game_stats_game_player_unique
    unique (game_id, player_id)
);

create index nba_player_game_stats_player_date_idx
  on public.nba_player_game_stats (
    player_id,
    game_date desc
  );

create index nba_player_game_stats_player_season_idx
  on public.nba_player_game_stats (
    player_id,
    season,
    game_type,
    game_date desc
  );

create index nba_player_game_stats_player_opponent_idx
  on public.nba_player_game_stats (
    player_id,
    opponent,
    game_date desc
  );

create index nba_player_game_stats_team_date_idx
  on public.nba_player_game_stats (
    team,
    game_date desc
  );

alter table public.nba_games enable row level security;
alter table public.nba_players enable row level security;
alter table public.nba_player_game_stats enable row level security;

create policy "Public can read NBA games"
  on public.nba_games
  for select
  to anon, authenticated
  using (true);

create policy "Public can read NBA players"
  on public.nba_players
  for select
  to anon, authenticated
  using (true);

create policy "Public can read NBA player game stats"
  on public.nba_player_game_stats
  for select
  to anon, authenticated
  using (true);
